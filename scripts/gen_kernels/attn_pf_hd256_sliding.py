class Driver:
    def __init__(self):
        import torch
        torch.cuda.init()
        torch.zeros(1, device="cuda")
        self.torch = torch
        self.cu = ctypes.CDLL("libcuda.so.1")

    def check(self, rc, what):
        if rc:
            name = ctypes.c_char_p()
            self.cu.cuGetErrorName(rc, ctypes.byref(name))
            raise RuntimeError(f"{what}: {name.value}")

    def function(self, image, entry):
        mod, fn = ctypes.c_void_p(), ctypes.c_void_p()
        self.check(self.cu.cuModuleLoadData(ctypes.byref(mod), image), "cuModuleLoadData")
        self.check(self.cu.cuModuleGetFunction(ctypes.byref(fn), mod, entry.encode()), entry)
        return mod, fn

    def global_u32(self, mod, name):
        ptr, size = ctypes.c_uint64(), ctypes.c_size_t()
        self.check(self.cu.cuModuleGetGlobal_v2(ctypes.byref(ptr), ctypes.byref(size), mod,
                                                name.encode()), name)
        out = ctypes.c_uint32()
        self.check(self.cu.cuMemcpyDtoH_v2(ctypes.byref(out), ptr, ctypes.c_size_t(4)), "dtoh")
        return out.value

    def prepare(self, fn, block, smem):
        self.check(self.cu.cuFuncSetAttribute(fn, 8, ctypes.c_int(smem)), "max dynamic smem")
        n = ctypes.c_int()
        self.check(self.cu.cuOccupancyMaxActiveBlocksPerMultiprocessor(
            ctypes.byref(n), fn, ctypes.c_int(block), ctypes.c_size_t(smem)), "occupancy")
        if n.value != 1:
            raise RuntimeError(f"occupancy {n.value} != 1 CTA/SM")

    def launch(self, fn, grid, block, smem, args):
        buf = ctypes.create_string_buffer(bytes(args), len(args))
        params = (ctypes.c_void_p * 1)(ctypes.addressof(buf))
        stream = ctypes.c_void_p(self.torch.cuda.current_stream().cuda_stream)
        self.check(self.cu.cuLaunchKernel(fn, grid, 1, 1, block, 1, 1, smem, stream, params,
                                          None), "cuLaunchKernel")
        self._keep = (buf, params)

    def tmap_kv3(self, base, rows, heads, box_rows):
        m = (ctypes.c_uint8 * 128)()
        gd = (ctypes.c_uint64 * 3)(D, rows, heads)
        gs = (ctypes.c_uint64 * 2)(D * 2, rows * D * 2)
        bd = (ctypes.c_uint32 * 3)(64, box_rows, 1)
        es = (ctypes.c_uint32 * 3)(1, 1, 1)
        self.check(self.cu.cuTensorMapEncodeTiled(m, 9, 3, ctypes.c_void_p(base), gd, gs, bd, es,
                                                  0, 3, 2, 0), "tmap")
        return bytes(m)


def pack(fields):
    fmt = "<" + "".join({"p": "Q", "f": "f", "u": "I"}[k] for k, _ in fields)
    return struct.pack(fmt, *[v for _, v in fields])


class Case:
    """Packet-shaped buffers. Q/O [seq_q][H][256]; K/V [slots][KVH][kv_stride][256], position p
    of a request at ring row p & kv_mask; requests (q0, qlen, slot, kvlen) packed in order."""

    def __init__(self, drv, H, KVH, window, requests, seq_q=None, kv_stride=None, ring=True,
                 slots=None, seed=0, qscale=None):
        torch = drv.torch
        self.drv, self.H, self.KVH, self.window, self.requests = drv, H, KVH, window, requests
        real = requests[-1][0] + requests[-1][1]
        self.seq_q = seq_q or real
        need = max(kvlen for _, _, _, kvlen in requests)
        if ring:
            span = max((window or kvlen) + qlen - 1 for _, qlen, _, kvlen in requests)
            self.kv_stride = kv_stride or 1 << max(span - 1, 63).bit_length()
            self.kv_mask = self.kv_stride - 1
        else:
            self.kv_stride = kv_stride or need
            self.kv_mask = 0xFFFFFFFF
        slots = slots or (max(r[2] for r in requests) + 1)
        g = torch.Generator(device="cuda").manual_seed(seed)
        bf = torch.bfloat16
        qs = qscale if qscale is not None else D ** -0.5
        self.q = (torch.randn(self.seq_q, H, D, device="cuda", generator=g) * qs).to(bf)
        self.k = torch.zeros(slots, KVH, self.kv_stride, D, device="cuda", dtype=bf)
        self.v = torch.zeros_like(self.k)
        self.lin = []
        for q0, qlen, slot, kvlen in requests:
            kl = torch.randn(kvlen, KVH, D, device="cuda", generator=g).to(bf)
            vl = torch.randn(kvlen, KVH, D, device="cuda", generator=g).to(bf)
            pos = torch.arange(kvlen, device="cuda")
            if ring:
                keep = pos >= kvlen - self.kv_stride  # what the ring still holds
                rows = pos[keep] & self.kv_mask
                self.k[slot][:, rows] = kl[keep].transpose(0, 1)
                self.v[slot][:, rows] = vl[keep].transpose(0, 1)
            else:
                self.k[slot][:, :kvlen] = kl.transpose(0, 1)
                self.v[slot][:, :kvlen] = vl.transpose(0, 1)
            self.lin.append((kl, vl))
        self.o = torch.full((self.seq_q, H, D), float("nan"), device="cuda", dtype=bf)
        flat = [len(requests)] + [x for r in requests for x in r]
        self.req = torch.tensor(flat, device="cuda", dtype=torch.int32)
        self.entries = torch.zeros(4096 * 24, device="cuda", dtype=torch.uint8)
        self.counters = torch.zeros(4096, device="cuda", dtype=torch.int32)
        self.scratch = torch.zeros(16, device="cuda", dtype=torch.float32)

    def map_table(self):
        """The packed launch's per-slot table of GEN_TMAP_KV_PAIR blobs (K map, V map; rank 3
        {256, kv_stride, KVH}, box {64, 32, 1}, 128B swizzle), as the packet supplies it."""
        if not hasattr(self, "table"):
            torch = self.drv.torch
            slots = self.k.shape[0]
            self.desc = torch.zeros(slots * 256 + 128, device="cuda", dtype=torch.uint8)
            base = (self.desc.data_ptr() + 127) // 128 * 128
            off = base - self.desc.data_ptr()
            ptrs = []
            for s in range(slots):
                km = self.drv.tmap_kv3(self.k[s].data_ptr(), self.kv_stride, self.KVH, 32)
                vm = self.drv.tmap_kv3(self.v[s].data_ptr(), self.kv_stride, self.KVH, 32)
                self.desc[off + 256 * s:off + 256 * s + 256] = torch.tensor(
                    list(km + vm), dtype=torch.uint8, device="cuda")
                ptrs.append(base + 256 * s)
            self.table = torch.tensor(ptrs, dtype=torch.int64, device="cuda")
        return self.table.data_ptr()

    def gen_args(self, scale=1.0, tma=False):
        p = lambda t: ("p", t.data_ptr())
        mapkv = self.map_table() if tma else 0
        return pack([p(self.req), p(self.scratch), p(self.scratch), p(self.q), p(self.k),
                     p(self.v), p(self.o), ("p", mapkv), p(self.entries), p(self.counters),
                     p(self.counters), ("u", self.seq_q), ("u", 0), ("u", 0),
                     ("u", self.kv_stride), ("u", self.kv_mask), ("f", scale), ("u", self.H),
                     ("u", self.KVH), ("u", self.window), ("u", 0)])

    def role14_args(self, tma=True):
        """Role 14's direct entry (PlowHd256Gqa2Direct, 112 B); `tma` builds the per-slot
        descriptor-pair table the packet supplies (box 32 rows)."""
        mapkv = self.map_table() if tma else 0
        p = lambda t: ("p", t.data_ptr())
        return pack([p(self.req), p(self.scratch), p(self.scratch), p(self.q), p(self.k),
                     p(self.v), p(self.o), ("p", mapkv), p(self.entries), p(self.counters),
                     p(self.counters), ("u", self.seq_q), ("u", 0), ("u", 0),
                     ("u", self.kv_stride), ("u", self.kv_mask), ("f", 1.0)])

    def reference_error(self, scale=1.0):
        """rel-L2 of every valid output row vs fp32 attention over the linear K/V; also checks
        padded rows are zero and nothing is NaN."""
        torch = self.drv.torch
        num = den = 0.0
        g = self.H // self.KVH
        for (q0, qlen, slot, kvlen), (kl, vl) in zip(self.requests, self.lin):
            pos = torch.arange(kvlen - qlen, kvlen, device="cuda")[:, None]
            kv = torch.arange(kvlen, device="cuda")[None, :]
            mask = kv <= pos
            if self.window:
                mask &= pos - kv < self.window
            for h in range(self.H):
                q = self.q[q0:q0 + qlen, h].float()
                s = (q @ kl[:, h // g].float().T) * scale
                s.masked_fill_(~mask, float("-inf"))
                ref = s.softmax(-1) @ vl[:, h // g].float()
                got = self.o[q0:q0 + qlen, h].float()
                num += (got - ref).pow(2).sum().item()
                den += ref.pow(2).sum().item()
        real = self.requests[-1][0] + self.requests[-1][1]
        tail = self.o[real:]
        tail_ok = bool((tail == 0).all().item()) if tail.numel() else True
        finite = bool(torch.isfinite(self.o[:real]).all().item())
        return math.sqrt(num / den), tail_ok, finite


def graph_time(torch, fns, reps=7):
    for f in fns:
        f()
    torch.cuda.synchronize()
    g = torch.cuda.CUDAGraph()
    s = torch.cuda.Stream()
    s.wait_stream(torch.cuda.current_stream())
    with torch.cuda.stream(s):
        with torch.cuda.graph(g, stream=s):
            for f in fns:
                f()
    torch.cuda.synchronize()
    g.replay()
    torch.cuda.synchronize()
    ts = []
    for _ in range(reps):
        e0, e1 = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
        e0.record()
        g.replay()
        e1.record()
        e1.synchronize()
        ts.append(e0.elapsed_time(e1) * 1000 / len(fns))
    return sorted(ts)[len(ts) // 2]


class Kernel:
    def __init__(self, drv, cubin, tma=False):
        self.drv, self.tma = drv, tma
        self.mod, self.fn = drv.function(Path(cubin).read_bytes(), "plow_gen_flash_prefill_direct")
        self.block = drv.global_u32(self.mod, "plow_gen_block")
        self.smem = drv.global_u32(self.mod, "plow_gen_arena_bytes")
        drv.prepare(self.fn, self.block, self.smem)

    def __call__(self, case, scale=1.0):
        self.drv.launch(self.fn, 132, self.block, self.smem, case.gen_args(scale, self.tma))


class Role14:
    def __init__(self, drv, cubin, tma=True):
        self.drv, self.tma = drv, tma
        self.mod, self.fn = drv.function(Path(cubin).read_bytes(),
                                         "plow_sm90a_pfattn_hd256_gqa2_bkv32_direct")
        self.smem = drv.global_u32(self.mod, "plow_arena_bytes_pfattn_hd256_gqa2_bkv32")
        drv.prepare(self.fn, 256, self.smem)

    def __call__(self, case):
        if not hasattr(case, "_r14"):
            case._r14 = case.role14_args(self.tma)
        self.drv.launch(self.fn, 132, 256, self.smem, case._r14)


def flop(H, window, requests):
    total = 0
    for _, qlen, _, kvlen in requests:
        for i in range(qlen):
            p = kvlen - qlen + i
            total += min(p + 1, window) if window else p + 1
    return 4 * H * D * total


