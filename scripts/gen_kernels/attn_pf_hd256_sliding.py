def creg(preg):
    # setmaxnreg pool: 384 threads x 168 at launch; the producer's release funds the consumers.
    return (168 + (168 - preg) * 128 // 256) // 8 * 8


def wgmma_inc():
    """Source of gen_attn_pf_hd256_wgmma.inc: one asm block per tile GEMM. Every descriptor is
    defined before wgmma.fence (a definition inside the stage serializes the wgmmas, ptxas C7513)
    without being hoisted out of the tile loop by the front end (that costs registers)."""
    def qk(n):
        r = n // 2
        acc = ", ".join(f"%{i}" for i in range(r))
        qa, kb, hi = r, r + 1, r + 2
        body = [".reg .pred pz, pa;", "setp.eq.u32 pz, 0, 1;", "setp.eq.u32 pa, 0, 0;",
                ".reg .b32 al<16>, bl<16>;", ".reg .b64 da<16>, db<16>;"]
        for kk in range(16):
            oa = (kk // 4) * 64 * 8 + (kk % 4) * 2
            ob = (kk // 4) * n * 8 + (kk % 4) * 2
            body += [f"add.u32 al{kk}, %{qa}, {oa};", f"add.u32 bl{kk}, %{kb}, {ob};",
                     f"mov.b64 da{kk}, {{al{kk}, %{hi}}};", f"mov.b64 db{kk}, {{bl{kk}, %{hi}}};"]
        body.append("wgmma.fence.sync.aligned;")
        body += [f"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{acc}}}, da{kk}, "
                 f"db{kk}, {'pz' if kk == 0 else 'pa'}, 1, 1, 0, 0;" for kk in range(16)]
        body.append("wgmma.commit_group.sync.aligned;")
        return (f"__device__ __forceinline__ void hd256_qk_n{n}(float* d, uint32_t qa, uint32_t kb,"
                f" uint32_t hi) {{\n    asm volatile(\n        \"{{\\n\"\n"
                + "".join(f'        "{line}\\n"\n' for line in body)
                + "        \"}\\n\"\n        : " + ", ".join(f'"+f"(d[{i}])' for i in range(r))
                + '\n        : "r"(qa), "r"(kb), "r"(hi)\n        : "memory");\n}\n')

    def pv(bn):
        # The descriptors come in as registers: this block is issued while the QK block is in
        # flight, so it must not define any wgmma input itself.
        r, ks = 128, bn // 16
        acc = ", ".join(f"%{i}" for i in range(r))
        body = ["wgmma.fence.sync.aligned;"]
        for kk in range(ks):
            a = ", ".join(f"%{r + 4 * kk + i}" for i in range(4))
            body.append(f"wgmma.mma_async.sync.aligned.m64n256k16.f32.bf16.bf16 {{{acc}}}, "
                        f"{{{a}}}, %{r + 4 * ks + kk}, 1, 1, 1, 1;")
        body.append("wgmma.commit_group.sync.aligned;")
        return (f"__device__ __forceinline__ void hd256_pv_bn{bn}(float* d, const uint32_t* a, "
                f"const uint64_t* vd) {{\n    asm volatile(\n        \"{{\\n\"\n"
                + "".join(f'        "{line}\\n"\n' for line in body)
                + "        \"}\\n\"\n        : " + ", ".join(f'"+f"(d[{i}])' for i in range(r))
                + "\n        : " + ", ".join(f'"r"(a[{i}])' for i in range(4 * ks))
                + ", " + ", ".join(f'"l"(vd[{i}])' for i in range(ks))
                + '\n        : "memory");\n}\n')

    head = ("// Generated by scripts/gen_kernels/attn_pf_hd256_sliding.py wgmma-inc; do not edit.\n"
            "// S = Q.K^T: 16 k-steps over K-major 128B-swizzled [4][rows][64] tiles.\n"
            "// O += P.V: P as register A fragments, V MN-major, LBO = one 64-column block.\n")
    return head + "".join(qk(n) for n in (32, 64)) + "".join(pv(bn) for bn in (32, 64))


def digest(cfg):
    """Generator identity of one config: the template sources plus the defines."""
    import hashlib
    h = hashlib.sha256()
    for path in (SOURCE, SOURCE.with_name("gen_attn_pf_hd256_wgmma.inc")):
        h.update(path.read_bytes())
    h.update(json.dumps(cfg, sort_keys=True).encode())
    return h.hexdigest()


def build(out, cfg):
    nvcc = os.environ.get("PLOW_NVCC", "/usr/local/cuda-12.9/bin/nvcc")
    cmd = [nvcc, "-ccbin", os.environ.get("PLOW_CXX", "/usr/bin/g++-14"), "-std=c++17",
           "-gencode", "arch=compute_90a,code=sm_90a", "-O3", "-cubin", "-Xptxas=-v",
           f"-I{REPO / 'runtime/common'}", f"-I{REPO / 'runtime/nvidia'}",
           f"-DGEN_BN={cfg['bn']}", f"-DGEN_KSTAGES={cfg['kstages']}",
           f"-DGEN_VSTAGES={cfg['vstages']}", f"-DGEN_PREG={cfg['preg']}",
           f"-DGEN_CREG={creg(cfg['preg'])}", "-o", str(out), str(SOURCE)]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode:
        raise RuntimeError(f"nvcc failed {cfg}:\n{res.stderr[-3000:]}")
    if "wgmma.mma_async instructions are serialized" in res.stderr:
        raise RuntimeError(f"ptxas serialized the wgmma pipeline for {cfg}")
    spill = sum(int(a) + int(b) for a, b in
                re.findall(r"(\d+) bytes spill stores, (\d+) bytes spill loads", res.stderr))
    return spill


