"""Emit crates/plowrt/src/tts/maya2_text/tables.rs from the live maya3.text tables (after rules/lexicon install).

  PYTHONPATH=<maya3 src> python scripts/tts/maya2_text_tables.py crates/plowrt/src/tts/maya2_text/tables.rs
"""
import sys
import unicodedata

import maya3.text as T
from maya3.text import rules as R
T.normalise_text("x", "hi")          # installs R9 + lexicon patches
mod = sys.modules["maya3.text.tn.normalize"]
from maya3.text.tn.indic_languages import LANGUAGES

out = []
w = out.append


def lit(s):
    r = []
    for c in s:
        cat = unicodedata.category(c)
        if c == "\\":
            r.append("\\\\")
        elif c == '"':
            r.append('\\"')
        elif cat[0] in "CZ" and c != " ":
            r.append("\\u{%x}" % ord(c))
        else:
            r.append(c)
    return '"' + "".join(r) + '"'


def slist(xs):
    return "&[" + ", ".join(lit(x) for x in xs) + "]"


def smap(d):
    return "&[" + ", ".join(f"({lit(str(k))}, {lit(v)})" for k, v in d.items()) + "]"


def imap(d):
    return "&[" + ", ".join(f"({k}, {lit(v)})" for k, v in d.items()) + "]"


w("// @generated by the maya3.text table dump (see the module header). Do not edit by hand.")
w("#![allow(clippy::all)]")
w("use super::lang::LangData;")
w("")

ORDER = ["en", "hi", "bn", "as", "gu", "kn", "ml", "mr", "or", "pa", "ta", "te"]
tables = {"en": mod.LANG, **LANGUAGES}
for code in ORDER:
    L = tables[code]
    assert len(L.ONES) == 100 and sorted(L.LETTERS) == [chr(65 + i) for i in range(26)]
    ex = {}
    for a in dir(L):
        if a.startswith("__") or callable(getattr(L, a)) or a in dir(mod.LangBase):
            continue
        ex[a] = getattr(L, a)
    lists, maps = {}, {}
    for k, v in ex.items():
        if isinstance(v, str):
            lists[k] = [v]
        elif isinstance(v, (list, tuple)):
            lists[k] = list(v)
        elif isinstance(v, (set, frozenset)):
            lists[k] = sorted(v)
        elif isinstance(v, dict):
            maps[k] = {str(a): b for a, b in v.items()}
        else:
            raise SystemExit(f"{code}.{k}: {type(v)}")
    name = code.upper()
    w(f"pub static {name}: LangData = LangData {{")
    w(f"    code: {lit(L.code)},")
    w(f"    ones: {slist(L.ONES)},")
    for f in ["HUNDRED", "THOUSAND", "LAKH", "CRORE", "TIME_ON_HOUR", "TIME_HM", "RANGE", "RANGE_TO", "RATIO",
              "POWER", "FRACTION", "DECADE_SHORT", "DECADE_FULL", "ORDINAL_SUFFIX", "NUMBER_WORD"]:
        w(f"    {f.lower()}: {lit(getattr(L, f))},")
    w(f"    letters: {slist([L.LETTERS[chr(65 + i)] for i in range(26)])},")
    w(f"    months: {slist(L.MONTHS)},")
    w(f"    month_aliases: {smap({k: str(v) for k, v in L.MONTH_ALIASES.items()})},")
    w(f"    sym: {smap(L.SYM)},")
    w(f"    periods: {smap(L.PERIODS)},")
    for f in ["TIME_MARKERS", "YEAR_WORDS", "ID_KEYWORDS", "ID_AFTER_WORDS", "LABEL_WORDS", "MINUTE_WORDS",
              "ORDINAL_INPUT_SUFFIXES"]:
        w(f"    {f.lower()}: {slist(getattr(L, f))},")
    for f in ["MARKER_SUFFIXES", "PERIOD_DETECT", "SCALE_WORDS", "CURRENCY_WORDS", "UNIT_WORDS", "ABBREV_UNITS",
              "AMPM_WORDS", "SINGULAR_NOUNS"]:
        w(f"    {f.lower()}: {smap(getattr(L, f))},")
    w(f"    ordinal_exceptions: {imap(L.ORDINAL_EXCEPTIONS)},")
    w(f"    count_one: {('Some(' + lit(L.COUNT_ONE) + ')') if L.COUNT_ONE else 'None'},")
    w("    extra_lists: &[" + ", ".join(f"({lit(k)}, {slist(v)})" for k, v in sorted(lists.items())) + "],")
    w("    extra_maps: &[" + ", ".join(f"({lit(k)}, {smap(v)})" for k, v in sorted(maps.items())) + "],")
    w("};")
    w("")

w("pub static LANGS: [&LangData; 12] = [" + ", ".join(f"&{c.upper()}" for c in ORDER) + "];")
w("")

consts = {
    "OTP_INPUT_WORDS": sorted(mod._OTP_INPUT_WORDS), "PAISA_INPUT_WORDS": sorted(mod._PAISA_INPUT_WORDS),
    "TAMIL_MONTHS": mod._TAMIL_MONTHS, "TAMIL_ORDINALS": mod._TAMIL_ORDINALS,
    "ACRONYM_WHITELIST": sorted(mod._ACRONYM_WHITELIST), "UNIT_INITIALISMS": sorted(mod._UNIT_INITIALISMS),
    "EN_SCALES": sorted(mod._EN_SCALES), "ID_KEYWORDS_EN": sorted(mod._ID_KEYWORDS_EN),
    "LABEL_WORDS_EN": sorted(mod._LABEL_WORDS_EN), "STREET_WORDS": sorted(mod._STREET_WORDS),
    "ELEMENTS": sorted(mod.Normalizer._ELEMENTS), "CHEM_WHITELIST": sorted(mod.Normalizer._CHEM_WHITELIST),
    "TA_MONTHS": R._TA_MONTHS, "URI_ACRONYMS": sorted(R._URI_ACRONYMS),
    "URI_ACR_PREFIX": list(R._URI_ACR_PREFIX), "URI_ACR_SUFFIX": list(R._URI_ACR_SUFFIX),
    "SPELL_UNITS": sorted(R._SPELL_UNITS),
}
for k, v in consts.items():
    w(f"pub static {k}: &[&str] = {slist(v)};")
w(f"pub static ENGLISH_MONTHS: &[(&str, u32)] = &[" + ", ".join(f"({lit(k)}, {v})" for k, v in mod._ENGLISH_MONTHS.items()) + "];")
from maya3.text import lexicon as LX
for k, v in {"AS_ATTACH": sorted(LX._AS_ATTACH), "AS_PP": list(LX._AS_PP)}.items():
    w(f"pub static {k}: &[&str] = {slist(v)};")
for k, rx in {"RE_PIN": R._PIN_RE, "RE_AMOUNT_AFTER": R._AMOUNT_AFTER, "RE_CURRENCY_BEFORE": R._CURRENCY_BEFORE,
              "RE_NUMBER_WORD_BEFORE": R._NUMBER_WORD_BEFORE, "RE_URI": R._URI_RE, "RE_EXPIRY": R._EXPIRY_RE,
              "RE_DATE_WORD": R._DATE_RE, "RE_EMOJI": mod._EMOJI_RE}.items():
    w(f"pub static {k}: &str = {lit(rx.pattern)};")
w(f"pub static DASH: &[(&str, &str)] = {smap(R.DASH)};")
w("")


def ranges(pred):
    rs, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            rs.append((start, cp - 1)); start = None
    if start is not None:
        rs.append((start, 0x10FFFF))
    return rs


def emit_ranges(name, rs):
    w(f"pub static {name}: &[(u32, u32)] = &[")
    for i in range(0, len(rs), 8):
        w("    " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in rs[i:i + 8]))
    w("];")


dec = ranges(str.isdecimal)
for a, b in dec:
    assert unicodedata.decimal(chr(a)) == 0 and all(unicodedata.decimal(chr(c)) == (c - a) % 10 for c in range(a, b + 1))
emit_ranges("ALNUM", ranges(str.isalnum))
emit_ranges("ALPHA", ranges(str.isalpha))
emit_ranges("DECIMAL", dec)
emit_ranges("DIGIT", ranges(str.isdigit))
emit_ranges("SPACE", ranges(str.isspace))
w(f"// Unicode {unicodedata.unidata_version} (the Python that generated this file)")

open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out) + "\n")
